## Converting sentences into features

def sent2features(sentence):
  sentence_features = []
  for i in range(len(sentence)):
    sentence_features.append(features(sentence, i))
  return sentence_features

# Making the input_train features
X_train_feature = []
for sent in X_train:
  X_train_feature.append(sent2features(sent))

X_val_feature = []
for sent in X_val:
  X_val_feature.append(sent2features(sent))

print(X_val_feature[0])

X_test_feature = []
