# Creating a Feature matrix for each word in a particular sentence
def features(sentence, i):
    current_word = sent[i]
    # Find the features of for the current word
    features = {
        "bias": 1.0, #Bias
        "word.lower()": current_word.lower(), # the word with all small letters
        "word[-3:]": current_word[-3:], #Last three letters of the word
        "word[-2:]": current_word[-2:], #Last two letters of the word
        "word[:2]": current_word[:2], # First two letters of the word
        "word[:3]": current_word[:3], # First three letters of the word
        "word.isupper()": current_word.isupper(), #All the elements in the word are captial or not
        "word.istitle()": current_word.istitle(),#Is the word is title
        "word.isdigit()": current_word.isdigit(),# Is it a number
    }

    if i > 0:
        prev_word = sentence[i-1]
        features.update({
            "prev_word.lower()": prev_word.lower(),
            "prev_word.istitle()": prev_word.istitle(),
            "prev_word.isupper()": prev_word.isupper(),
        })
    else:
        features["BOS"] = True   # Beginning of sentence

    if i < len(sentence)-1:
        nxt_word = sentence[i+1]
        features.update({
            "next_word.lower()": nxt_word.lower(),
            "next_word.istitle()": nxt_word.istitle(),
            "next_word.isupper()": nxt_word.isupper(),
        })
    else:
        features["EOS"] = True   # End of sentence

    return features

