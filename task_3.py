#Applying Conditional Random Fields
import sklearn_crfsuite

crf = sklearn_crfsuite.CRF(
    algorithm="lbfgs",
    c1=0.1, #c1 = L1-Regularizer
    c2=0.1, #c2 = L2-Regularizer
    max_iterations=100,
    all_possible_transitions=True,
)

crf.fit(X_train_feature, y_train_updated)

from sklearn_crfsuite import metrics

y_pred = crf.predict(X_test_feature)

