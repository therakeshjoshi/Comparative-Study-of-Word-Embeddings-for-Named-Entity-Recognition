import json
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim

import pandas as pd
import numpy as np

from scipy.sparse import csr_matrix
from sklearn.decomposition import TruncatedSVD
from sklearn.preprocessing import normalize
from sklearn.feature_extraction.text import TfidfTransformer
from sklearn.metrics.pairwise import cosine_similarity
from sklearn.metrics import accuracy_score, f1_score

addr = "updated_vocab_document_dict.json"

with open(addr, "r", encoding="utf-8") as f:
    dataOfFile = json.load(f)

print("Total vocabulary words:", len(dataOfFile))

Task2_vocabulary = list(dataOfFile.keys())
word_to_idx = {word: idx for idx, word in enumerate(Task2_vocabulary)}
idx_to_word = {idx: word for word, idx in word_to_idx.items()}

V = len(Task2_vocabulary)

rows = []
cols = []
values = []

doc_id_map = {}
doc_counter = 0

for word in Task2_vocabulary:
    word_idx = word_to_idx[word]

    for entry in dataOfFile[word]:
        doc_id = entry[0]
        passage = entry[1]

        if doc_id not in doc_id_map:
            doc_id_map[doc_id] = doc_counter
            doc_counter += 1

        col_idx = doc_id_map[doc_id]

        tokens = passage.split()
        count = tokens.count(word)

        rows.append(word_idx)
        cols.append(col_idx)
        values.append(count)

D = doc_counter
X_raw = csr_matrix((values, (rows, cols)), shape=(V, D))

print("Raw Matrix Shape:", X_raw.shape)

#Part 1 - TF-IDF Weighting


tfidf = TfidfTransformer(norm=None)
X_tfidf = tfidf.fit_transform(X_raw)

print("TF-IDF Matrix Shape:", X_tfidf.shape)

#Part 2 - SVD on RAW vs TF-IDF


best_d = 100
raw_svd = TruncatedSVD(n_components=best_d, random_state=42)
raw_emb= raw_svd.fit_transform(X_raw)
raw_emb = normalize(raw_emb)

tfidf_svd = TruncatedSVD(n_components=best_d, random_state=42)
tfidf_emb = tfidf_svd.fit_transform(X_tfidf)
tfidf_emb = normalize(tfidf_emb)

def neighbors(emb, word, top_k=5):
    if word not in word_to_idx:
        # idx = word_to_idx[word]
        # vector = emb[idx].reshape(1, -1)
        # similarities = cosine_similarity(vector, emb)[0]        
        return "Not there in Vocabulary"
        

    idx = word_to_idx[word]
    vector = emb[idx].reshape(1, -1)
    similarities = cosine_similarity(vector, emb)[0]

    indices = similarities.argsort()[-top_k-1:][::-1]

    results = []
    for loopcounter in indices:
        if loopcounter != idx:
            results.append((idx_to_word[loopcounter], similarities[loopcounter]))

    return results[:top_k]

