from datasets import load_dataset
dataset = load_dataset("conll2003")

def embedding(word):
    if word in word_to_idx:
        # print(f"\nWORD: {word}")
        return tfidf_emb[word_to_idx[word]]
    else:
        return np.zeros(best_d)

tag_list = dataset["train"].features["ner_tags"].feature.names
num_tags = len(tag_list)

def prepare_split(split):
    X_data = []
    y_data = []

    for example in dataset[split]:
        tokens = example["tokens"]
        tags = example["ner_tags"]

        for token, tag in zip(tokens, tags):
            X_data.append(embedding(token))
            y_data.append(tag)

    return torch.tensor(X_data, dtype=torch.float32), torch.tensor(y_data)

X_train, y_train = prepare_split("train")
X_test, y_test = prepare_split("test")

class MLP(nn.Module):
    def __init__(self, input_dim, num_classes):
        super().__init__()
        self.model = nn.Sequential(
            nn.Linear(input_dim, 256),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(256, num_classes)
        )

    def forward(self, x):
        return self.model(x)

model = MLP(best_d, num_tags)

criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(model.parameters(), lr=0.001)

epochs = 5

for epoch in range(epochs):
    model.train()
    optimizer.zero_grad()

    outputs = model(X_train)
    loss = criterion(outputs, y_train)

    loss.backward()
    optimizer.step()

    print(f"Epoch {epoch+1}, Loss: {loss.item()}")

"""## **Quality Check 2: Train final MLP using TF-IDF SVD vectors and report performance**"""

model.eval()
with torch.no_grad():
    outputs = model(X_test)
    predictions = torch.argmax(outputs, dim=1)

acc = accuracy_score(y_test.numpy(), predictions.numpy())
f1 = f1_score(y_test.numpy(), predictions.numpy(), average="macro")

print("Token Accuracy:", acc)
print("Macro F1:", f1)

